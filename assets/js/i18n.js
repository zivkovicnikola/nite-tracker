var jezik = "sr"
var azurirajPrikaz = null

function prevedi(kljuc){
  let recnikJezika = recnik[jezik]
  if(recnikJezika[kljuc] != undefined){
    return recnikJezika[kljuc]
  }
  
  if(recnik.sr[kljuc] != undefined){
    return recnik.sr[kljuc]
  }
  return kljuc
}

function primeniPrevode(){
  $("[data-i18n]").each(function(){
    let kljuc = $(this).attr("data-i18n")
    let tekst = prevedi(kljuc)
    if(tekst.indexOf("\n") != -1){
      $(this).html(tekst.split("\n").join("<br>"))
    } else {
      $(this).text(tekst)
    }
  })

  $("[data-i18n-ph]").each(function(){
    $(this).attr("placeholder", prevedi($(this).attr("data-i18n-ph")))
  })

  $("[data-i18n-aria]").each(function(){
    $(this).attr("aria-label", prevedi($(this).attr("data-i18n-aria")))
  })
}

function obeleziDugmeJezika(){
  $("#langSwitch .lang-btn").each(function(){
    if($(this).attr("data-lang") == jezik){
      $(this).addClass("active")
    } else {
      $(this).removeClass("active")
    }
  })
}

function postaviJezik(noviJezik){
  if(recnik[noviJezik] == undefined){ return }
  jezik = noviJezik
  localStorage.setItem("nt_lang", noviJezik)

  $("html").attr("lang", noviJezik)
  let kljucNaslova = $("body").attr("data-title-key")
  if(!kljucNaslova){ kljucNaslova = "doc.title.home" }
  document.title = prevedi(kljucNaslova)

  primeniPrevode()
  obeleziDugmeJezika()

  if(azurirajPrikaz != null){
    azurirajPrikaz()
  }
}

function pokreniJezik(){
  let zapamcen = localStorage.getItem("nt_lang")
  if(zapamcen != null && recnik[zapamcen] != undefined){
    jezik = zapamcen
  } else {
    jezik = "sr"
  }

  $("html").attr("lang", jezik)
  let kljucNaslova = $("body").attr("data-title-key")
  if(!kljucNaslova){ kljucNaslova = "doc.title.home" }
  document.title = prevedi(kljucNaslova)

  primeniPrevode()
  obeleziDugmeJezika()

  $("#langSwitch .lang-btn").on("click", function(){
    postaviJezik($(this).attr("data-lang"))
  })
}
